def gen_normalize(rng: random.Random) -> str:
    parts = [HEADER]
    N = neologdn.normalize

    # per-char, default options
    cases = [(ch, N(ch)) for ch in CANDIDATES]
    parts.append(case_block("normalize: per-char (defaults)", "normalize(input)", "normalize", cases))

    # curated, all tilde modes x remove_space
    for tilde, tilde_mbt in TILDES:
        for remove_space in (True, False):
            label = f"tilde={tilde} remove_space={mbt_bool(remove_space)}"
            call = f"normalize(input, remove_space={mbt_bool(remove_space)}, tilde={tilde_mbt})"
            cs = [(s, N(s, remove_space=remove_space, tilde=tilde)) for s in NORMALIZE_CURATED]
            parts.append(case_block(f"normalize {label}: curated", call, "normalize", cs))

    # repeat option
    repeat_inputs = [
        "うまああああああああああああい",
        "かわいいいいいるい",
        "オラオラオラオラーッ",
        "無駄無駄無駄無駄ァ",
        "ｗｗｗｗｗｗ",
        "！！！！？？？",
        "ﾊﾊﾊﾊﾊﾊ",
        "隣の客はよく柿食う客だ、隣の客はよく柿食う客だ、隣の客はよく柿食う客だ、言えた！",
    ]
    for repeat in (1, 2, 3):
        for max_len in (8, 0, 2):
            call = f"normalize(input, repeat={repeat}, max_repeat_substr_length={max_len})"
            cs = [(s, N(s, repeat=repeat, max_repeat_substr_length=max_len)) for s in repeat_inputs]
            parts.append(
                case_block(
                    f"normalize repeat={repeat} max_repeat_substr_length={max_len}",
                    call,
                    "normalize",
                    cs,
                )
            )

    # seeded fuzz: defaults
    fuzz = []
    for _ in range(600):
        n = rng.randint(0, 14)
        s = "".join(rng.choice(FUZZ_ALPHABET) for _ in range(n))
        fuzz.append((s, N(s)))
    parts.append(case_block("normalize: fuzz (defaults)", "normalize(input)", "normalize", fuzz))

    # seeded fuzz: other option combos
    for tilde, tilde_mbt in TILDES:
        for remove_space in (True, False):
            if tilde == "remove" and remove_space:
                continue
            fz = []
            for _ in range(80):
                n = rng.randint(0, 14)
                s = "".join(rng.choice(FUZZ_ALPHABET) for _ in range(n))
                fz.append((s, N(s, remove_space=remove_space, tilde=tilde)))
            call = f"normalize(input, remove_space={mbt_bool(remove_space)}, tilde={tilde_mbt})"
            parts.append(
                case_block(
                    f"normalize tilde={tilde} remove_space={mbt_bool(remove_space)}: fuzz",
                    call,
                    "normalize",
                    fz,
                )
            )
    return "\n".join(parts)


# ---------------------------------------------------------------------------
# shorten_repeat (neologdn)
# ---------------------------------------------------------------------------


def gen_repeat(rng: random.Random) -> str:
    parts = [HEADER]
    S = neologdn.shorten_repeat
    fixed = [
        ("うまああああああああああああい", 7, 0),
        ("かわいいいいいるい", 6, 0),
        ("オラオラオラオラーッ", 2, 0),
        ("無駄無駄無駄無駄ァ", 1, 0),
        ("隣の客はよく柿食う客だ、隣の客はよく柿食う客だ、隣の客はよく柿食う客だ、言えた！", 1, 0),
        ("隣の客はよく柿食う客だ、隣の客はよく柿食う客だ、隣の客はよく柿食う客だ、言えた！", 1, 11),
        ("ああああ", 2, 8),
        ("ababab", 1, 8),
        ("😀😀😀😀", 1, 8),
        ("𠮷𠮷𠮷a", 2, 8),
        ("", 1, 8),
    ]
    for threshold, max_len in [(1, 8), (2, 8), (3, 8), (1, 0), (2, 2), (1, 1)]:
        cs = [(t, S(t, r, m)) for (t, r, m) in fixed if r == threshold and m == max_len]
        alphabet = list("abあい😀")
        for _ in range(60):
            n = rng.randint(0, 14)
            s = "".join(rng.choice(alphabet) for _ in range(n))
            cs.append((s, S(s, threshold, max_len)))
        call = f"shorten_repeat(input, {threshold}, max_repeat_substr_length={max_len})"
        parts.append(
            case_block(
                f"shorten_repeat threshold={threshold} max_repeat_substr_length={max_len}",
                call,
                "shorten_repeat",
                cs,
            )
        )
    # fixed cases whose params were not covered above
    covered = {(1, 8), (2, 8), (3, 8), (1, 0), (2, 2), (1, 1)}
    rest = [(t, r, m) for (t, r, m) in fixed if (r, m) not in covered]
    for i, (t, r, m) in enumerate(rest):
        parts.append(
            "\n".join(
                [
                    "///|",
                    f"test {mbt_str(f'shorten_repeat: fixed #{i}')} {{",
                    f"  assert_eq(shorten_repeat({mbt_str(t)}, {r}, max_repeat_substr_length={m}), "
                    f"{mbt_str(S(t, r, m))})",
                    "}",
                ]
            )
            + "\n"
        )
    return "\n".join(parts)


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    rng = random.Random(SEED)
    files = {
        "golden_kana_wbtest.mbt": gen_kana(),
        "golden_width_wbtest.mbt": gen_width(rng),
        "golden_normalize_wbtest.mbt": gen_normalize(rng),
        "golden_repeat_wbtest.mbt": gen_repeat(rng),
    }
    for name, content in files.items():
        path = os.path.join(OUT_DIR, name)
        with open(path, "w", encoding="utf-8", newline="\n") as fp:
            fp.write(content)
        print(f"wrote {os.path.relpath(path)} ({content.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
